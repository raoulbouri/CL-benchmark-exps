"""Phase 1 deliverable: docs/COST_MODEL.md from the Phase 1 results (measured, not estimated).

python scripts/report_phase1.py        (libero env; reads results/*.json with spec.phase == "p1")
"""
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from cl_bench import ROOT  # noqa: E402

FULL = {"libero_10": 10}
# Scale factors from micro schedule to the default full schedule, per codebase (see run specs).
FULL_SCHEDULE = {"dmpel": {"epochs": 10, "recall_epochs": 10}, "clare": {"steps": 20000, "disc_steps": 2000}}


def fmt(x, nd=1):
    return "–" if x is None else (f"{x:.{nd}f}" if isinstance(x, (int, float)) else str(x))


def main():
    rows = []
    for f in sorted(glob.glob(str(ROOT / "results" / "*.json"))):
        r = json.load(open(f))
        if r.get("spec", {}).get("phase") != "p1":
            continue
        t = r.get("timings", {})
        per_task = t.get("per_task_train_min") or t.get("per_task_wall_min") or []
        acc = (r.get("accounting", {}).get("per_task") or [{}])[-1]
        mem_bytes = acc.get("replay_bytes_on_disk", 0) + (acc.get("growth_bytes") or acc.get("adapter_bytes") or 0)
        rows.append({
            "name": r["name"], "status": r.get("status"), "tasks": r.get("tasks_done"),
            "wall_h": r.get("wall_hours"), "min_per_task": (sum(per_task) / len(per_task)) if per_task else None,
            "eval_min_per_task": (sum(t["per_task_eval_success_min"]) / len(t["per_task_eval_success_min"])) if t.get("per_task_eval_success_min") else None,
            "peak_gb": t.get("peak_train_mem_gb"), "mem_mb": mem_bytes / 1e6 if mem_bytes else None,
            "c_diag": [r["c_matrix"][k][k] for k in range(r.get("tasks_done") or 0)] if r.get("c_matrix") else None,
            "wandb": (r.get("wandb") or {}).get("url"),
        })
    out = ["# Cost model (Phase 1, measured)", "",
           "Generated by `scripts/report_phase1.py` from `results/*.json` (phase p1). Micro-streams: 2 LIBERO-Long tasks on short",
           "schedules (DMPEL-codebase: 2 epochs; CLARE-codebase: 2,000 steps). These numbers are for costing only, not results.", "",
           "| Run | Status | Tasks | Wall h | Min/task | Eval min/task | Peak train GB | Memory kept (MB) | Just-learned success | W&B |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| `{r['name']}` | {r['status']} | {r['tasks']} | {fmt(r['wall_h'], 2)} | {fmt(r['min_per_task'])} | "
                   f"{fmt(r['eval_min_per_task'])} | {fmt(r['peak_gb'])} | {fmt(r['mem_mb'])} | {r['c_diag']} | [run]({r['wandb']}) |")
    p = ROOT / "docs" / "COST_MODEL.md"
    marker = "## Projection to full schedules"
    keep = None
    if p.exists() and marker in p.read_text():
        tail = p.read_text().split(marker, 1)[1]
        if "fill in after review" not in tail:  # keep a hand-written projection across regeneration
            keep = marker + tail
    out += [""] + ((keep.rstrip("\n").split("\n")) if keep else [marker + " (fill in after review)", "",
            "Write the scaled numbers and the Phase 2-5 re-estimate here (see docs/COST_MODEL.md history)."])
    p.write_text("\n".join(out) + "\n")
    print(p.read_text())


if __name__ == "__main__":
    main()
